[CmdletBinding()]
param(
    [string[]]$GroupId,

    [ValidateRange(1, 30)]
    [int]$AuditDays = 30,

    [switch]$SkipAuditLog,

    [string]$MappingCsvPath,

    [switch]$Disconnect
)

$ErrorActionPreference = 'Stop'

# ---------------------------------------------------------------------------
# Graph session cleanup. Runs on every exit path: normal end, 'no groups found',
# and (via the trap below) a terminating error. It only acts on a connection that
# this script created, so a session you were already using is never touched.
# ---------------------------------------------------------------------------
$connectedByScript = $false

function Complete-GraphSession {
    param(
        [bool]$CreatedConnection,
        [bool]$SignOut
    )

    if (-not $CreatedConnection) { return }

    if ($SignOut) {
        $null = Disconnect-MgGraph
        Write-Host "Disconnected from Graph." -ForegroundColor Green
    }
    else {
        Write-Host -ForegroundColor Yellow "You are still connected to Graph. Disconnect with Disconnect-MgGraph if you are done."
    }
}

trap {
    Complete-GraphSession -CreatedConnection $connectedByScript -SignOut $Disconnect.IsPresent
    throw $_
}

# ---------------------------------------------------------------------------
# 1. Connect (reuse an existing session if there is one —
#    otherwise prompt for delegated login)
# ---------------------------------------------------------------------------
$requiredScopes = @('Group.Read.All', 'GroupMember.Read.All', 'Organization.Read.All')
if (-not $SkipAuditLog) { $requiredScopes += 'AuditLog.Read.All' }

$context = Get-MgContext
if (-not $context) {
    Write-Host "No existing Graph session found — connecting interactively." -ForegroundColor Cyan
    Connect-MgGraph -Scopes $requiredScopes -NoWelcome
    $connectedByScript = $true
}
else {
    Write-Host "Reusing existing Graph session ($($context.Account))." -ForegroundColor Cyan

    # Courtesy check only — app-only sessions expose roles, not scopes, so skip those.
    if ($context.AuthType -eq 'Delegated') {
        $missingScopes = $requiredScopes | Where-Object { $_ -notin $context.Scopes }
        if ($missingScopes) {
            Write-Warning "The current session may be missing scope(s): $($missingScopes -join ', '). Calls may fail — reconnect with Connect-MgGraph -Scopes if they do."
        }
    }
}

# ---------------------------------------------------------------------------
# 2. Get the dynamic groups that use memberOf
# ---------------------------------------------------------------------------
Write-Host "Retrieving dynamic groups..." -ForegroundColor Cyan

$groupProperties = 'Id', 'DisplayName', 'MembershipRule', 'MembershipRuleProcessingState', 'CreatedDateTime', 'AssignedLicenses'

if ($GroupId) {
    $groups = foreach ($id in $GroupId) {
        Get-MgGroup -GroupId $id -Property $groupProperties
    }
}
else {
    $groups = Get-MgGroup -All -ConsistencyLevel eventual -CountVariable groupCount `
        -Filter "groupTypes/any(c:c eq 'DynamicMembership')" `
        -Property $groupProperties
}

$groups = @($groups | Where-Object { $_.MembershipRule -match 'memberof' })

if ($groups.Count -eq 0) {
    Write-Warning "No dynamic groups using memberOf were found."
    Complete-GraphSession -CreatedConnection $connectedByScript -SignOut $Disconnect.IsPresent
    return
}

Write-Host "Found $($groups.Count) dynamic group(s) using memberOf." -ForegroundColor Cyan

# ---------------------------------------------------------------------------
# 3. Resolve license SKU GUIDs -> friendly product names, via Microsoft's
#    official mapping file. Falls back to a well-known community-maintained
#    mirror if Microsoft's own download link doesn't respond — its URL embeds
#    a rotating document ID and periodically moves. Only runs when at least
#    one group actually has licenses, so unlicensed groups skip the download.
#    If no mapping can be obtained, licenses fall back to SkuPartNumber.
# ---------------------------------------------------------------------------
$skuNameLookup = @{}      # SkuId -> friendly product name (from the mapping CSV)
$skuPartNumbers = @{}     # SkuId -> SkuPartNumber (fallback, straight from the tenant)
$unmappedSkus = [System.Collections.Generic.HashSet[string]]::new()

$licensedGroupCount = @($groups | Where-Object { $_.AssignedLicenses.Count -gt 0 }).Count

if ($licensedGroupCount -eq 0) {
    Write-Host "No group has licenses assigned — skipping license name mapping." -ForegroundColor DarkGray
}
else {
    Write-Host "Retrieving subscribed SKUs..." -ForegroundColor Cyan
    foreach ($sku in (Get-MgSubscribedSku -All)) {
        $skuPartNumbers[$sku.SkuId.ToString()] = $sku.SkuPartNumber
    }

    $mapping = $null

    if ($MappingCsvPath -and (Test-Path $MappingCsvPath)) {
        Write-Host "Using cached mapping file: $MappingCsvPath" -ForegroundColor Cyan
        $mapping = Import-Csv $MappingCsvPath
    }
    else {
        if ($MappingCsvPath) {
            Write-Warning "Mapping file '$MappingCsvPath' was not found — downloading a fresh copy instead."
        }

        Write-Host "Downloading the current product name mapping from Microsoft..." -ForegroundColor Cyan
        $tempMapping = Join-Path ([System.IO.Path]::GetTempPath()) 'M365-License-Mapping.csv'
        $officialUrl = 'https://download.microsoft.com/download/e/3/e/e3e9faf2-f28b-490a-9ada-c6089a1fc5b0/Product%20names%20and%20service%20plan%20identifiers%20for%20licensing.csv'
        $fallbackUrl = 'https://raw.githubusercontent.com/merill/license/main/license.csv'

        $previousProgressPreference = $ProgressPreference
        $ProgressPreference = 'SilentlyContinue'
        try {
            try {
                Invoke-WebRequest -Uri $officialUrl -OutFile $tempMapping -UseBasicParsing
            }
            catch {
                Write-Warning "Microsoft's official download link didn't respond — falling back to the community-maintained mirror (merill/license)."
                Invoke-WebRequest -Uri $fallbackUrl -OutFile $tempMapping -UseBasicParsing
            }
            $mapping = Import-Csv $tempMapping
            Write-Host "Saved a copy to $tempMapping — pass it via -MappingCsvPath next time to skip the download." -ForegroundColor DarkGray
        }
        catch {
            Write-Warning "Could not obtain the product name mapping ($($_.Exception.Message)). Licenses will be shown as SKU part numbers."
        }
        finally {
            $ProgressPreference = $previousProgressPreference
        }
    }

    # The mapping file has one row per SERVICE PLAN, so the same product GUID repeats
    # many times — de-duplicate down to one friendly name per SKU GUID.
    if ($mapping) {
        foreach ($row in ($mapping | Sort-Object GUID -Unique)) {
            if ($row.GUID -and -not $skuNameLookup.ContainsKey($row.GUID)) {
                $skuNameLookup[$row.GUID] = $row.Product_Display_Name
            }
        }
    }
}

# ---------------------------------------------------------------------------
# 4. Read the group-management audit log ONCE and index it per target group.
#    The Graph group resource has no lastModified property, so this is the only
#    source for "last changed" — and it only goes back as far as the tenant's
#    audit retention (30 days P1/P2, 7 days Free).
#    A failure here is not fatal: the audit columns simply stay empty.
# ---------------------------------------------------------------------------
$auditByGroup = @{}
$membershipActivities = @('Add member to group', 'Remove member from group')

if ($SkipAuditLog) {
    Write-Host "Skipping audit log (-SkipAuditLog)." -ForegroundColor DarkGray
}
else {
    $since = (Get-Date).ToUniversalTime().AddDays(-$AuditDays).ToString('yyyy-MM-ddTHH:mm:ssZ')
    Write-Host "Reading GroupManagement audit events since $since..." -ForegroundColor Cyan

    try {
        $auditEvents = Get-MgAuditLogDirectoryAudit -All `
            -Filter "category eq 'GroupManagement' and activityDateTime ge $since"

        foreach ($auditEvent in $auditEvents) {
            foreach ($target in $auditEvent.TargetResources) {
                if ($target.Type -eq 'Group' -and $target.Id) {
                    if (-not $auditByGroup.ContainsKey($target.Id)) {
                        $auditByGroup[$target.Id] = [System.Collections.Generic.List[object]]::new()
                    }
                    $auditByGroup[$target.Id].Add($auditEvent)
                }
            }
        }
        Write-Host "Indexed $(@($auditEvents).Count) audit event(s)." -ForegroundColor DarkGray
    }
    catch {
        Write-Warning "Could not read the audit log ($($_.Exception.Message)). LastGroupChange / LastMembershipChange will be empty."
    }
}

# ---------------------------------------------------------------------------
# 5. Build one object per group. Multi-value fields (owners, licenses, source
#    groups) are joined into a single string so the output exports cleanly to
#    CSV/Excel instead of showing up as "System.Object[]".
# ---------------------------------------------------------------------------
$total = $groups.Count
$i = 0

$results = foreach ($group in $groups) {
    $i++
    Write-Progress -Activity "Building memberOf group inventory" -Status "$i of $total — $($group.DisplayName)" -PercentComplete (($i / $total) * 100)
    Write-Verbose "Processing $($group.DisplayName) ($($group.Id))"

    # Owners (users show a UPN; service principals only have a display name)
    $owners = @(Get-MgGroupOwner -GroupId $group.Id -All | ForEach-Object {
            $upn = $_.AdditionalProperties['userPrincipalName']
            if ($upn) { $upn } else { $_.AdditionalProperties['displayName'] }
        })

    # Licenses assigned to the group itself (group-based licensing).
    # Friendly name -> SkuPartNumber -> raw GUID, in that order of preference.
    $licenses = @($group.AssignedLicenses | ForEach-Object {
            $skuId = $_.SkuId.ToString()
            if ($skuNameLookup.ContainsKey($skuId)) {
                $skuNameLookup[$skuId]
            }
            elseif ($skuPartNumbers.ContainsKey($skuId)) {
                [void]$unmappedSkus.Add($skuId)
                $skuPartNumbers[$skuId]
            }
            else {
                [void]$unmappedSkus.Add($skuId)
                $skuId
            }
        })

    # Source groups referenced in the rule; a deleted source group is worth knowing about
    $sourceIds = [regex]::Matches($group.MembershipRule, '[0-9a-fA-F]{8}-([0-9a-fA-F]{4}-){3}[0-9a-fA-F]{12}') |
        ForEach-Object { $_.Value } | Select-Object -Unique
    $sourceNames = foreach ($sourceId in $sourceIds) {
        try { (Get-MgGroup -GroupId $sourceId -Property DisplayName).DisplayName }
        catch { "<not found: $sourceId>" }
    }

    # Audit-derived "last modified" (empty = nothing inside the retention window)
    $groupEvents = if ($auditByGroup.ContainsKey($group.Id)) { $auditByGroup[$group.Id] } else { @() }
    $lastChange = $groupEvents | Where-Object { $_.ActivityDisplayName -notin $membershipActivities } |
        Sort-Object ActivityDateTime -Descending | Select-Object -First 1
    $lastMembership = $groupEvents | Where-Object { $_.ActivityDisplayName -in $membershipActivities } |
        Sort-Object ActivityDateTime -Descending | Select-Object -First 1

    [PSCustomObject]@{
        DisplayName           = $group.DisplayName
        ObjectId              = $group.Id
        GroupKind             = if ($group.MembershipRule -match 'device\.memberof') { 'Device' } else { 'User' }
        MembershipRule        = $group.MembershipRule
        SourceGroups          = $sourceNames -join '; '
        ProcessingState       = $group.MembershipRuleProcessingState
        CreatedDateTime       = $group.CreatedDateTime
        MemberCount           = Get-MgGroupMemberCount -GroupId $group.Id -ConsistencyLevel eventual
        Owners                = $owners -join '; '
        OwnerCount            = $owners.Count
        HasLicenses           = $licenses.Count -gt 0
        Licenses              = $licenses -join '; '
        LastGroupChange       = $lastChange.ActivityDateTime
        LastGroupChangeAction = $lastChange.ActivityDisplayName
        LastMembershipChange  = $lastMembership.ActivityDateTime
        AuditWindowDays       = if ($SkipAuditLog) { $null } else { $AuditDays }
    }
}

Write-Progress -Activity "Building memberOf group inventory" -Completed

if ($unmappedSkus.Count -gt 0) {
    Write-Warning "No friendly name found for $($unmappedSkus.Count) SKU(s) — their SkuPartNumber (or GUID) is shown instead: $($unmappedSkus -join ', ')"
}

Write-Host "Done. Returning $(@($results).Count) group record(s) to the pipeline.`n" -ForegroundColor Green
Complete-GraphSession -CreatedConnection $connectedByScript -SignOut $Disconnect.IsPresent

# ---------------------------------------------------------------------------
# 6. Emit to the pipeline. Run bare -> PowerShell's default table view.
#    Piped -> flows straight into Export-Csv / Export-Excel / Out-GridView /
#    Where-Object / whatever comes next.
# ---------------------------------------------------------------------------
$results
