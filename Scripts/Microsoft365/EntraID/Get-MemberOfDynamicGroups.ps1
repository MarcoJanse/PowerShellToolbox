<#
.SYNOPSIS
Inventories Entra ID dynamic groups whose membership rule uses the memberOf operator
and returns them to the pipeline — displayed in the console by default, or piped to
Export-Csv / Export-Excel / Out-GridView / whatever you want.

.DESCRIPTION
Microsoft is retiring the memberOf rule operator on November 3, 2026. After that date,
dynamic groups that use it stop updating and stay in their last known state. This
script helps you decide what to do with each group by collecting, per group:

  - the rule itself and the source groups it references (deleted source groups are
    flagged as "<not found: id>")
  - owners, member count and processing state
  - licenses assigned to the group, shown by friendly product name (for example
    "Microsoft 365 E3") and joined into a single string so the output exports
    cleanly — no "System.Object[]"
  - the most recent group change and the most recent membership change, taken from
    the Entra audit log

This script has no export logic of its own — it just emits clean PSCustomObjects.
Run it bare and PowerShell's default formatter displays a table in the console.
Pipe it anywhere else and the objects flow through normally.

.PARAMETER GroupId
Optional. One or more group object IDs to inspect instead of every dynamic group in
the tenant. Useful for a first test run on a handful of groups. Groups that do not
use memberOf are skipped.

.PARAMETER AuditDays
How many days of audit log to read for the LastGroupChange / LastMembershipChange
columns. Range 1-30, default 30. Entra only keeps audit logs for 30 days (P1/P2) or
7 days (Free), so this cannot look further back than that.

.PARAMETER SkipAuditLog
Skip the audit log entirely (no AuditLog.Read.All scope needed). The
LastGroupChange, LastGroupChangeAction and LastMembershipChange columns stay empty.

.PARAMETER MappingCsvPath
Optional path to a locally cached copy of Microsoft's "Product names and service
plan identifiers for licensing" CSV. If omitted, the script downloads the current
version and saves a copy to your temp folder — pass that path back in on a later run
to skip the download entirely. The mapping is only needed (and only downloaded) when
at least one of the groups has licenses assigned.

.PARAMETER Disconnect
Optional. Disconnect from Microsoft Graph (Disconnect-MgGraph) when the script is done,
but only if this script created the connection itself. A session you were already
connected to is never disconnected. Without this switch, the script prints a reminder
instead when it created the connection.

.NOTES
Requires: Microsoft.Graph.Authentication, Microsoft.Graph.Groups,
          Microsoft.Graph.Identity.DirectoryManagement, Microsoft.Graph.Reports
Scopes:   Group.Read.All, GroupMember.Read.All, Organization.Read.All,
          AuditLog.Read.All (not needed with -SkipAuditLog)
          All read-only, consistent with a least-privilege audit identity. Reading
          audit logs may additionally require a directory role such as Reports Reader.

If you're already connected to Graph, this script reuses that session automatically —
it will not reconnect or prompt (it only warns if the session looks like it is missing
a scope). To run this standalone with certificate auth instead of interactive login,
replace the Connect-MgGraph line in section 1 with your usual
-ClientId/-TenantId/-CertificateThumbprint pattern.

License names: if the mapping file cannot be downloaded or a SKU is not in it yet
(brand-new SKUs), the script falls back to the internal SkuPartNumber (e.g.
"ENTERPRISEPACK") and warns instead of stopping.

An empty LastGroupChange / LastMembershipChange means "no activity inside the audit
retention window", NOT "never changed". The Graph group resource has no
lastModifiedDateTime property, so the audit log is the only source. Verify on one
active group that dynamic membership processing actually appears in the audit log
before relying on LastMembershipChange.

