<#
.SYNOPSIS
    Builds a per-user license matrix (one True/False column per licensed product) and
    returns it to the pipeline — displayed in the console by default, or piped to
    Export-Csv / Export-Excel / Out-GridView / whatever you want.

.DESCRIPTION
    Fixes the "System.Object[]" problem you get from a naive AssignedLicenses export by
    building one explicit column per unique product license found in the tenant, keyed
    on the friendly display name (not the raw GUID or internal SkuPartNumber code name
    like "SPE_F1"). Designed for spotting redundant/overlapping licensing — e.g. a user
    who holds both Microsoft 365 F3 and a standalone Exchange Online Plan 1, or both
    Microsoft 365 Business Premium and a standalone Defender for Office 365 Plan 1.

    This script has no export logic of its own — it just emits clean PSCustomObjects.
    Run it bare and PowerShell's default formatter displays a table in the console.
    Pipe it anywhere else and the objects flow through normally.

.PARAMETER IncludeDisabledUsers
    Include disabled (blocked sign-in) accounts. Off by default — most licensing/overlap
    audits only care about active users.

.PARAMETER MappingCsvPath
    Optional path to a locally cached copy of Microsoft's "Product names and service
    plan identifiers for licensing" CSV. If omitted, the script downloads the current
    version and saves a copy to %TEMP% — pass that path back in on a later run to skip
    the download entirely.

.NOTES
    Requires: Microsoft.Graph.Users, Microsoft.Graph.Identity.DirectoryManagement
    Scopes:   User.Read.All, Organization.Read.All (delegated or application — both
              read-only, consistent with a least-privilege audit identity)

    If you're already connected to Graph, this script reuses that session
    automatically — it will not reconnect or prompt. To run this standalone with
    certificate auth instead of interactive login, replace the Connect-MgGraph line in
    section 1 with your usual -ClientId/-TenantId/-CertificateThumbprint pattern.

    With DisplayName + UPN + AccountEnabled + LicenseCount + one column per product,
    a wide tenant can easily produce 15-20+ columns. A bare console table will get
    truncated to fit your terminal width. For actually spotting overlap, Out-GridView
    (see examples below) is usually more useful than the plain table — it's built
    exactly for "wide object, want to filter/sort visually."

