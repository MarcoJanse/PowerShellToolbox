[CmdletBinding()]
param(
    [switch]$IncludeDisabledUsers,
    [string]$MappingCsvPath
)

$ErrorActionPreference = 'Stop'

# ---------------------------------------------------------------------------
# 1. Connect (reuse an existing session if there is one —
#    otherwise prompt for delegated login)
# ---------------------------------------------------------------------------
if (-not (Get-MgContext)) {
    Write-Host "No existing Graph session found — connecting interactively." -ForegroundColor Cyan
    Connect-MgGraph -Scopes "User.Read.All", "Organization.Read.All" -NoWelcome
}
else {
    Write-Host "Reusing existing Graph session ($((Get-MgContext).Account))." -ForegroundColor Cyan
}

# Courtesy heads-up about Export-Excel — purely informational, doesn't block anything.
if (Get-Module -ListAvailable -Name ImportExcel) {
    Write-Host "ImportExcel module detected — you can pipe the output to Export-Excel." -ForegroundColor DarkGray
}
else {
    Write-Host "Tip: 'Install-Module ImportExcel' if you want to pipe the output straight to a formatted .xlsx via Export-Excel." -ForegroundColor DarkGray
}

# ---------------------------------------------------------------------------
# 2. Get the SKUs actually present in this tenant
# ---------------------------------------------------------------------------
Write-Host "Retrieving subscribed SKUs..." -ForegroundColor Cyan
$tenantSkus = Get-MgSubscribedSku -All

# ---------------------------------------------------------------------------
# 3. Resolve SKU GUIDs -> friendly product names, via Microsoft's official
#    mapping file. Falls back to a well-known community-maintained mirror if
#    Microsoft's own download link doesn't respond — its URL embeds a
#    rotating document ID and periodically moves.
# ---------------------------------------------------------------------------
if ($MappingCsvPath -and (Test-Path $MappingCsvPath)) {
    Write-Host "Using cached mapping file: $MappingCsvPath" -ForegroundColor Cyan
    $mapping = Import-Csv $MappingCsvPath
}
else {
    Write-Host "Downloading the current product name mapping from Microsoft..." -ForegroundColor Cyan
    $tempMapping = Join-Path $env:TEMP "M365-License-Mapping.csv"
    $officialUrl = "https://download.microsoft.com/download/e/3/e/e3e9faf2-f28b-490a-9ada-c6089a1fc5b0/Product%20names%20and%20service%20plan%20identifiers%20for%20licensing.csv"
    $fallbackUrl = "https://raw.githubusercontent.com/merill/license/main/license.csv"
    $ProgressPreference = 'SilentlyContinue'
    try {
        Invoke-WebRequest -Uri $officialUrl -OutFile $tempMapping -UseBasicParsing
    }
    catch {
        Write-Warning "Microsoft's official download link didn't respond — falling back to the community-maintained mirror (merill/license)."
        Invoke-WebRequest -Uri $fallbackUrl -OutFile $tempMapping -UseBasicParsing
    }
    $mapping = Import-Csv $tempMapping
    Write-Host "Saved a copy to $tempMapping — pass it via -MappingCsvPath next time to skip the download." -ForegroundColor DarkGray
}

# The mapping file has one row per SERVICE PLAN, so the same product GUID repeats many
# times — de-duplicate down to one friendly name per SKU GUID.
$skuNameLookup = @{}
foreach ($row in ($mapping | Sort-Object GUID -Unique)) {
    if ($row.GUID -and -not $skuNameLookup.ContainsKey($row.GUID)) {
        $skuNameLookup[$row.GUID] = $row.Product_Display_Name
    }
}

# Resolve the friendly name for every SKU actually in this tenant. Fall back to the
# internal SkuPartNumber (e.g. "SPE_F1") if a brand-new SKU isn't in the mapping yet —
# this happens for SKUs Microsoft has shipped very recently.
$skuFriendlyNames = @{}
foreach ($sku in $tenantSkus) {
    $friendly = $skuNameLookup[$sku.SkuId]
    if (-not $friendly) {
        Write-Warning "No friendly name found for SkuId $($sku.SkuId) (SkuPartNumber: $($sku.SkuPartNumber)) — using the part number instead."
        $friendly = $sku.SkuPartNumber
    }
    $skuFriendlyNames[$sku.SkuId] = $friendly
}

$uniqueLicenseNames = $skuFriendlyNames.Values | Sort-Object -Unique
Write-Host "Found $($uniqueLicenseNames.Count) unique licensed products in this tenant." -ForegroundColor Cyan

# Precompute a reverse lookup (friendly name -> the SkuId(s) that map to it) once,
# rather than re-deriving it for every single user in the loop below.
$nameToSkuIds = @{}
foreach ($kvp in $skuFriendlyNames.GetEnumerator()) {
    if (-not $nameToSkuIds.ContainsKey($kvp.Value)) { $nameToSkuIds[$kvp.Value] = @() }
    $nameToSkuIds[$kvp.Value] += $kvp.Key
}

# ---------------------------------------------------------------------------
# 4. Pull every user's assigned licenses and build one True/False column per
#    unique product. This is what avoids "System.Object[]" — that text is
#    just PowerShell's default .ToString() on the raw AssignedLicenses array;
#    building explicit named columns sidesteps it entirely.
# ---------------------------------------------------------------------------
Write-Host "Retrieving users (this can take a while on larger tenants)..." -ForegroundColor Cyan
$users = Get-MgUser -All -Property "Id,DisplayName,UserPrincipalName,AccountEnabled,AssignedLicenses"

if (-not $IncludeDisabledUsers) {
    $users = $users | Where-Object { $_.AccountEnabled }
}

$total = @($users).Count
$i = 0
$results = foreach ($user in $users) {
    $i++
    Write-Progress -Activity "Building license matrix" -Status "$i of $total" -PercentComplete (($i / $total) * 100)

    $assignedSkuIds = @($user.AssignedLicenses).SkuId

    $row = [ordered]@{
        DisplayName       = $user.DisplayName
        UserPrincipalName = $user.UserPrincipalName
        AccountEnabled    = $user.AccountEnabled
        LicenseCount      = @($user.AssignedLicenses).Count
    }

    foreach ($licenseName in $uniqueLicenseNames) {
        $row[$licenseName] = [bool]($assignedSkuIds | Where-Object { $_ -in $nameToSkuIds[$licenseName] })
    }

    [PSCustomObject]$row
}
Write-Progress -Activity "Building license matrix" -Completed

Write-Host "Done. Returning $($results.Count) user records to the pipeline.`n" -ForegroundColor Green

# ---------------------------------------------------------------------------
# 5. Emit to the pipeline. Run bare -> PowerShell's default table view.
#    Piped -> flows straight into Export-Csv / Export-Excel / Out-GridView /
#    Where-Object / whatever comes next.
# ---------------------------------------------------------------------------
$results