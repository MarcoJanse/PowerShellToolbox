    $searchDir = $PSScriptRoot
    while ($searchDir -and -not $script:ScriptPath) {
        $hit = Get-ChildItem -LiteralPath $searchDir -Filter $scriptName -File -Recurse -ErrorAction SilentlyContinue |
            Select-Object -First 1
